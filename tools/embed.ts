// Write src/shader.ts from tandem.wgsl, so the package needs no file loading at runtime.
// Usage: deno run --allow-read --allow-write tools/embed.ts
const wgsl = await Deno.readTextFile(new URL("../tandem.wgsl", import.meta.url));
const out = `// Generated by tools/embed.ts from tandem.wgsl. Do not edit.\nexport const SHADER = ${
  JSON.stringify(wgsl)
};\n`;
await Deno.writeTextFile(new URL("../src/shader.ts", import.meta.url), out);
